import json, pathlib, re, unicodedata, sys
root = pathlib.Path(sys.argv[1])
d = root / 'content/voicetecx-legal'
P = lambda c: unicodedata.category(c).startswith('P')

def fix_cjk_bold(s):
    # CommonMark won't close ** after punctuation when a CJK letter follows (or open before
    # punctuation after one). Move edge punctuation outside the bold span; the words are unchanged.
    def rep(m):
        inner = m.group(1)
        lead = ''
        while inner and P(inner[0]): lead += inner[0]; inner = inner[1:]
        trail = ''
        while inner and P(inner[-1]): trail = inner[-1] + trail; inner = inner[:-1]
        return f'{lead}**{inner}**{trail}' if inner else m.group(0)
    return re.sub(r'\*\*([^*\n]+?)\*\*', rep, s)

out = {}
for f in ['privacy', 'terms', 'refund']:
    out[f] = {l: (d / f'{f}.{l}.md').read_text() for l in ['en', 'zh']}
    out[f]['zh'] = fix_cjk_bold(out[f]['zh'])
src = ("// Generated by scripts/gen-voicetecx-legal.py from content/voicetecx-legal/*.md\n"
       "// (drafts from tecxmate/voicetecx legal/, commit 2530324). Edit the .md files, then regenerate.\n"
       "// The facts are the VoiceTecx team's wording; keep them as written.\n\n"
       "export type LegalDoc = \"privacy\" | \"terms\" | \"refund\"\n\n"
       "export const VOICETECX_LEGAL: Record<LegalDoc, { en: string; zh: string }> = "
       + json.dumps(out, ensure_ascii=False, indent=2) + "\n")
(root / 'lib/voicetecx-legal.ts').write_text(src)
